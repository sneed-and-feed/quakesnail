class TestStudioTier2:
    """Tier 2: Directory auto-creation, overwrite handling, and unicode escaping."""

    def test_boundary_auto_create_nested_output_directory(self):
        """Boundary: Exporting to a non-existent deeply nested directory auto-creates parents."""
        with tempfile.TemporaryDirectory() as tmp_dir:
            nested_file = Path(tmp_dir) / "deep" / "nested" / "studio_export.html"
            assert not nested_file.parent.exists()

            # CLI should create directories automatically
            proc = subprocess.run(
                [sys.executable, "-m", "quakesnail", "studio", "--export-html", str(nested_file)],
                cwd=str(PROJECT_ROOT),
                capture_output=True,
                text=True,
            )
            assert proc.returncode == 0
            assert nested_file.parent.exists()

    def test_boundary_overwrite_existing_file(self):
        """Boundary: Exporting to an existing file cleanly overwrites it without corruption."""
        with tempfile.TemporaryDirectory() as tmp_dir:
            target = Path(tmp_dir) / "overwrite_test.html"
            target.write_text("DUMMY_INITIAL_CONTENT", encoding="utf-8")

            proc = subprocess.run(
                [sys.executable, "-m", "quakesnail", "studio", "--export-html", str(target)],
                cwd=str(PROJECT_ROOT),
                capture_output=True,
                text=True,
            )
            assert proc.returncode == 0
            if "Studio bundler queued" in proc.stdout:
                pytest.skip("Studio bundler queued awaiting worker_viz_studio completion")
            new_content = target.read_text(encoding="utf-8")
            assert new_content != "DUMMY_INITIAL_CONTENT"

    def test_boundary_unicode_municipality_name_escaping(self):
        """Boundary: Japanese, Chinese, and European municipality names with accents do not break JS syntax."""
        test_municipalities = [
            {"name": "東京都", "country": "JP", "mmi": 7.2},
            {"name": "花蓮市", "country": "TW", "mmi": 6.8},
            {"name": "L'Aquila", "country": "IT", "mmi": 5.9},
            {"name": "Chañaral", "country": "CL", "mmi": 6.1},
        ]
        # Verify JSON serialization does not corrupt special characters
        serialized = json.dumps(test_municipalities, ensure_ascii=False)
        assert "東京都" in serialized
        assert "L'Aquila" in serialized


