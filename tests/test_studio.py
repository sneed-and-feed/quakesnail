class TestStudioTier1:
    """Tier 1: HTML file size, zero CDN dependencies, and tactical HUD validation."""

    def test_f18_studio_html_file_size_greater_than_50kb(self):
        """F18: Verify exported studio HTML file size is strictly > 50 KB (50,000 bytes)."""
        with tempfile.TemporaryDirectory() as tmp_dir:
            out_file = Path(tmp_dir) / "studio.html"
            studio_path = get_or_export_studio_html(out_file)
            if not studio_path.exists() or studio_path.stat().st_size < 50_000:
                pytest.skip("Studio exporter not yet generated by Milestone 4 worker")

            size_bytes = studio_path.stat().st_size
            assert size_bytes > 50_000, f"Studio size {size_bytes} B was <= 50,000 B"

    def test_f18_zero_external_cdn_dependencies(self):
        """F18: Verify complete offline self-containment with ZERO external CDN references."""
        with tempfile.TemporaryDirectory() as tmp_dir:
            out_file = Path(tmp_dir) / "studio.html"
            studio_path = get_or_export_studio_html(out_file)
            if not studio_path.exists() or studio_path.stat().st_size < 50_000:
                pytest.skip("Studio HTML not yet generated")

            html = studio_path.read_text(encoding="utf-8")

            # Check for remote script tags: <script src="http..." or <script src="https..."
            remote_scripts = re.findall(r'<script[^>]+src=["\'](https?://[^"\']+)["\']', html, re.IGNORECASE)
            assert len(remote_scripts) == 0, f"Found external CDN scripts: {remote_scripts}"

            # Check for remote stylesheets: <link ... href="http..."
            remote_links = re.findall(r'<link[^>]+href=["\'](https?://[^"\']+)["\']', html, re.IGNORECASE)
            assert len(remote_links) == 0, f"Found external CDN stylesheets: {remote_links}"

    def test_f18_offline_scenarios_payload_bundling(self):
        """F18: Verify scenarios are bundled into window.QUAKESNAIL_OFFLINE_SCENARIOS."""
        with tempfile.TemporaryDirectory() as tmp_dir:
            out_file = Path(tmp_dir) / "studio.html"
            studio_path = get_or_export_studio_html(out_file)
            if not studio_path.exists() or studio_path.stat().st_size < 50_000:
                pytest.skip("Studio HTML not yet generated")

            html = studio_path.read_text(encoding="utf-8")
            assert "QUAKESNAIL_OFFLINE_SCENARIOS" in html, (
                "Missing window.QUAKESNAIL_OFFLINE_SCENARIOS injection in studio HTML"
            )

    def test_f26_tactical_hud_zero_people_felt_elements(self):
        """F26: STRICT AUDIT: Tactical HUD contains ZERO 'people felt' columns or labels."""
        with tempfile.TemporaryDirectory() as tmp_dir:
            out_file = Path(tmp_dir) / "studio.html"
            studio_path = get_or_export_studio_html(out_file)
            if not studio_path.exists() or studio_path.stat().st_size < 50_000:
                pytest.skip("Studio HTML not yet generated")

            html = studio_path.read_text(encoding="utf-8").lower()
            forbidden = [
                "people felt",
                "countfelt",
                "countstrong",
                "possibly felt by",
                "possibly heavily felt by",
            ]
            for phrase in forbidden:
                assert phrase not in html, f"Forbidden phrase '{phrase}' found in studio HTML!"

    def test_f23_f25_webgl2_canvas_and_rings_elements(self):
        """F23-F25: Verify presence of 3D WebGL2 canvas and expanding wavefront shaders."""
        with tempfile.TemporaryDirectory() as tmp_dir:
            out_file = Path(tmp_dir) / "studio.html"
            studio_path = get_or_export_studio_html(out_file)
            if not studio_path.exists() or studio_path.stat().st_size < 50_000:
                pytest.skip("Studio HTML not yet generated")

            html = studio_path.read_text(encoding="utf-8")
            assert "<canvas" in html.lower(), "Missing WebGL2 canvas element"
            assert "webgl" in html.lower() or "gl" in html.lower()


