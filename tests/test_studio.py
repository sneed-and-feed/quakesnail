class TestStudioTier4:
    """Tier 4: Extract embedded JavaScript and validate with node --check to ensure zero syntax errors."""

    def test_realworld_node_check_javascript_syntax(self):
        """
        Validate all embedded JavaScript blocks in the studio HTML via `node --check`.
        Guarantees zero SyntaxError in single-file offline deployment.
        """
        studio_path = get_or_export_studio_html()
        if not studio_path.exists() or studio_path.stat().st_size < 50_000:
            pytest.skip("Studio HTML not yet generated")

        html = studio_path.read_text(encoding="utf-8")
        js_blocks = extract_javascript_blocks(html)
        assert len(js_blocks) > 0, "No inline <script> blocks found in studio HTML"

        # Check each JS block using `node --check`
        for idx, block in enumerate(js_blocks):
            if not block.strip():
                continue
            with tempfile.NamedTemporaryFile("w", suffix=".js", delete=False, encoding="utf-8") as temp_js:
                temp_js.write(block)
                temp_js_path = temp_js.name

            try:
                proc = subprocess.run(
                    ["node", "--check", temp_js_path],
                    capture_output=True,
                    text=True,
                )
                assert proc.returncode == 0, (
                    f"JavaScript syntax error in script block #{idx}:\n{proc.stderr}"
                )
            finally:
                if os.path.exists(temp_js_path):
                    os.unlink(temp_js_path)
