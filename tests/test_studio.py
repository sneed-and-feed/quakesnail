class TestStudioTier3:
    """Tier 3: Pairwise combinations across scenario payloads and export configurations."""

    @pytest.mark.parametrize("scenario_count", [1, 3, 5])
    def test_pairwise_offline_scenario_payload_serialization(self, scenario_count):
        """Pairwise: Validate JSON scenario array packing with variable scenario counts."""
        scenarios = {
            f"scenario_{i}": {
                "name": f"Synthetic Event {i}",
                "magnitude": 6.0 + i * 0.5,
                "epicenter": [35.0 + i, 138.0 + i, 15.0],
                "stations": [{"id": f"STA{s}", "pga": 0.05 * s} for s in range(5)],
            }
            for i in range(scenario_count)
        }
        js_payload = f"window.QUAKESNAIL_OFFLINE_SCENARIOS = {json.dumps(scenarios)};"
        assert len(js_payload) > 100
        # Parse back to verify validity
        extracted = json.loads(js_payload.replace("window.QUAKESNAIL_OFFLINE_SCENARIOS = ", "").rstrip(";"))
        assert len(extracted) == scenario_count


