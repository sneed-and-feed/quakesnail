from __future__ import annotations

import json
import os
import re
import subprocess
import sys
import tempfile
from pathlib import Path
from typing import Dict, List, Optional

import pytest

PROJECT_ROOT = Path(__file__).resolve().parent.parent
if str(PROJECT_ROOT) not in sys.path:
    sys.path.insert(0, str(PROJECT_ROOT))


def extract_javascript_blocks(html_content: str) -> List[str]:
    """Extract all inline JavaScript blocks from <script> tags in HTML."""
    # Pattern to match inline <script> blocks (excluding external src)
    script_pattern = re.compile(r"<script(?![^>]*\bsrc\b)[^>]*>(.*?)</script>", re.DOTALL | re.IGNORECASE)
    return script_pattern.findall(html_content)


def get_or_export_studio_html(output_path: Optional[Path] = None) -> Path:
    """Helper to locate or export the portable studio HTML."""
    default_studio = PROJECT_ROOT / "studio" / "quakesnail_portable_studio.html"
    if default_studio.exists() and default_studio.stat().st_size > 50_000:
        return default_studio

    if output_path is None:
        temp_dir = Path(tempfile.mkdtemp())
        target = temp_dir / "quakesnail_test_studio.html"
    else:
        target = output_path

    # Try exporting via CLI: python -m quakesnail studio --export-html <target>
    proc = subprocess.run(
        [sys.executable, "-m", "quakesnail", "studio", "--export-html", str(target)],
        cwd=str(PROJECT_ROOT),
        capture_output=True,
        text=True,
    )
    if target.exists() and target.stat().st_size > 50_000:
        return target

    # Fallback to direct import if available
    try:
        from quakesnail.studio.bundler import export_portable_studio
        export_portable_studio(str(target))
        return target
    except (ImportError, AttributeError):
        pass

    return target


